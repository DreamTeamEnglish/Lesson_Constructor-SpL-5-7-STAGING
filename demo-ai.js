  function normalizedText(s){
    return String(s??'')
      .replace(/[\uFFFE\uFFFF]/g,'-')
      .replace(/\u00AD/g,'');
  }

  function inline(s){
    let x=esc(normalizedText(s));
    x=x.replace(/\*\*(.+?)\*\*/g,'<strong>$1</strong>');
    x=x.replace(/(^|[^*])\*([^*\n]+?)\*(?!\*)/g,'$1<em>$2</em>');
    x=x.replace(/(^|[^_])_([^_\n]+?)_(?!_)/g,'$1<em>$2</em>');
    return x;
  }

  function tableCells(line){
    let x=String(line||'').trim();
    if(x.startsWith('|'))x=x.slice(1);
    if(x.endsWith('|'))x=x.slice(0,-1);
    return x.split('|').map(c=>c.trim());
  }

  function isTableSep(line){
    const cells=tableCells(line);
    return cells.length>1&&cells.every(c=>/^:?-{3,}:?$/.test(c.replace(/\s/g,'')));
  }

  function format(text){
    const lines=String(text||'').replace(/```(?:markdown|md|text)?/gi,'').split(/\r?\n/);
    let html='',list='',i=0;
    const close=()=>{if(list){html+=`</${list}>`;list=''}};
    while(i<lines.length){
      const line=lines[i].trim();
      if(!line){close();i++;continue}
      if(/^---+$/.test(line)){close();i++;continue}

      if(line.includes('|') && i+1<lines.length && isTableSep(lines[i+1])){
        close();
        const heads=tableCells(line);
        i+=2;
        const rows=[];
        while(i<lines.length){
          const row=lines[i].trim();
          if(!row||!row.includes('|')||/^#{1,4}\s+/.test(row))break;
          rows.push(tableCells(row));i++;
        }
        html+=`<div class="v24-table-wrap"><table><thead><tr>${heads.map(c=>`<th>${inline(c)}</th>`).join('')}</tr></thead><tbody>${rows.map(r=>`<tr>${heads.map((_,j)=>`<td>${inline(r[j]||'')}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`;
        continue;
      }

      const h=line.match(/^#{1,4}\s+(.+)$/);
      if(h){close();html+=`<h3>${inline(h[1])}</h3>`;i++;continue}

      const phase=line.match(/^(P[1-6]\s*[·.\-]\s*.+)$/i);
      if(phase){close();html+=`<h3 class="v24-phase-title">${inline(phase[1])}</h3>`;i++;continue}

      const blockTitle=line.match(/^(Блок\s+\d+\s*[:·.\-]\s*.+)$/i);
      if(blockTitle){close();html+=`<h4>${inline(blockTitle[1])}</h4>`;i++;continue}

      const boldPair=line.match(/^\*\*(.+?):\s*\*\*\s*(.*)$/);
      if(boldPair){
        close();
        html+=`<p class="v24-label-line"><strong>${inline(boldPair[1])}:</strong>${boldPair[2]?` ${inline(boldPair[2])}`:''}</p>`;
        i++;
        continue;
      }

      const bullet=line.match(/^[-*•]\s+(.+)$/);
      if(bullet){
        if(list!=='ul'){close();html+='<ul>';list='ul'}
        html+=`<li>${inline(bullet[1])}</li>`;i++;continue
      }

      const ordered=line.match(/^\d+[.)]\s+(.+)$/);
      if(ordered){
        if(list!=='ol'){close();html+='<ol>';list='ol'}
        html+=`<li>${inline(ordered[1])}</li>`;i++;continue
      }

      close();
      const pair=line.match(/^([^:]{2,70}):\s*(.+)$/);
      html+=pair?`<p class="v24-label-line"><strong>${inline(pair[1])}:</strong> ${inline(pair[2])}</p>`:`<p>${inline(line)}</p>`;
      i++;
    }
    close();
    return html;
  }


